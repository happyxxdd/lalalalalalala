"""
Временный замер (не часть сайта).
Считает ширину плейсхолдеров по таблице глифов, откалиброванной на
рендере из скриншота пользователя (шрифт Manrope, 16px):
  «+7 900 000-00-00» в скриншоте занял 126px, таблица даёт 126.7px;
  «или» — 33px в рендере против 31.9px по таблице.
Доступная ширина поля по тому же скриншоту: 262px.
"""
W = {  # ширина глифа в px при 16px Manrope
    '+': 9.4, '7': 8.9, '9': 8.9, '0': 8.9, ' ': 4.4, '-': 5.3, '.': 4.4,
    'и': 7.9, 'л': 7.3, 'п': 8.9, 'р': 8.4, 'г': 8.6, 'с': 8.0, 'ы': 8.6,
    'к': 8.0, 'а': 8.4, 'т': 7.2, 'е': 8.2, 'ь': 7.0, 'н': 8.9, 'я': 8.0
}

def width(text):
    return sum(W.get(ch, 8.4) for ch in text)

AVAILABLE = 262
CANDIDATES = [
    ('было (в скриншоте обрезалось)', '+7 900 000-00-00 или пригласительная ссылка'),
    ('просили', '+7 900 000-00-00 или пригл. ссылка'),
    ('со слэшем (запасной)', '+7 900 000-00-00 / пригл. ссылка'),
]

print(f"доступно в поле: {AVAILABLE}px")
for name, text in CANDIDATES:
    w = width(text)
    print(f"  {name:<28} {len(text):>2} зн.  ~{w:6.1f}px  "
          f"{'влезает' if w <= AVAILABLE else 'НЕ влезает'} (запас {AVAILABLE - w:+.0f}px)")
